// Package must implements helper functions to simplify repetitive error handling.
//
// Of, Of2, and Of3 are the generic helpers and work for any type. Typed helpers
// such as Int and RuneInt are kept for compatibility.
//
// Mainly there are 3 ways to handle errors.
//
//   - Return errors.
//   - Panic.
//   - Handle errors.
//
// This package provides a way to hide error handling and focus on the main
// logic. The code may look a lot cleaner. The downside is that the explicit
// return statement is hidden to look unclear.
//
// Well written Go code indents error flow and the function should be short
// enough, so this package shouldn't be required. (But Go 2 draft seems to adopt
// this idea.)
//
// By default, must panics. If you'd like to return error by default (like Go 2
// try proposal), defer ReturnErr(&err) in the beginning. If you'd like to wrap
// the error, you may use HandleErrorf(&err, "format string", args...), and this
// works with both normal error return and try-like must.
//
// You may customize error handling more flexible way using HandleErr.
package must

import "runtime"

// CheckErr panics if err is non-nil and put the filename and line number and
// skip is the number of stack fragments to ascend. This function could be used
// to write custom must functions.
func CheckErr(err error, skip int) {
	if err != nil {
		_, file, line, _ := runtime.Caller(skip)
		panic(wrap{err, file, line})
	}
}

// Nil panics if err is non-nil.
func Nil(err error) {
	CheckErr(err, 2)
}

// Any panics if err is non-nil and returns interface{}.
func Any(v0 interface{}, err error) interface{} {
	return Of(v0, err)
}

// Of panics if err is non-nil and returns v.
func Of[T any](v T, err error) T {
	CheckErr(err, 2)
	return v
}

// Of2 panics if err is non-nil and returns a and b.
func Of2[A, B any](a A, b B, err error) (A, B) {
	CheckErr(err, 2)
	return a, b
}

// Of3 panics if err is non-nil and returns a, b, and c.
func Of3[A, B, C any](a A, b B, c C, err error) (A, B, C) {
	CheckErr(err, 2)
	return a, b, c
}

